d = docx.Document(SRC)
P = d.paragraphs

def rewrite(i, text):
    """把段落 i 的文字整体替换为 text, 保留首个run的字体与段落格式。"""
    p = P[i]
    if not p.runs:
        p.add_run(text); return
    p.runs[0].text = text
    for r in p.runs[1:]:
        r._element.getparent().remove(r._element)

def sub(i, old, new):
    rewrite(i, P[i].text.replace(old, new))

# ---- 标题与资助信息 ----
